-- Replica local MINIMA para la Practica 12. No es la base real de Supabase.
-- Las columnas base de cotizacion_leads (tabla de la web) se infieren de las funciones del repo.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
END $$;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$ SELECT coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb; $$;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT (auth.jwt()->>'sub')::uuid; $$;
GRANT USAGE ON SCHEMA auth,public TO authenticated,anon;
GRANT EXECUTE ON FUNCTION auth.uid(),auth.jwt() TO authenticated,anon;
CREATE TABLE public.profiles(id uuid PRIMARY KEY REFERENCES auth.users(id), activo boolean DEFAULT true);
CREATE TABLE public.cotizacion_leads(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_viaje text, destino text NOT NULL, fecha_ida date, fecha_vuelta date,
  adultos integer DEFAULT 1, ninos integer DEFAULT 0, nombre text, correo text, telefono text,
  comentarios text, estado text NOT NULL DEFAULT 'enviada', respuesta_asesor text,
  creado_en timestamptz NOT NULL DEFAULT now());
